import crypto from 'crypto';
import { Types } from 'mongoose';
import { PhysicalAsset, IPhysicalAsset } from '../db/models/PhysicalAsset';
import { generateAssetQrUrl } from './qr.service';

export interface FactoryProvisioningInput {
  entityId: string | Types.ObjectId;
  facilityId: string | Types.ObjectId;
  parentBoxId?: string | Types.ObjectId;
  name?: string;
  macAddress: string;
  imei?: string;
  simNumber?: string;
  hardwareRevision?: string;
  notes?: string;
}

export interface NvsConfigBundle {
  version: number;
  nodeId: string;
  assetCode: string;
  macAddress: string;
  deviceKey: string;
  apiEndpoint: string;
  reportingIntervalSeconds: number;
  hardwareRevision: string;
  provisionedAt: string;
}

export interface FactoryProvisioningResult {
  asset: IPhysicalAsset;
  rawDeviceKey: string;
  deviceKeyHash: string;
  nvsConfig: NvsConfigBundle;
  nvsHeaderC: string;
  qrCodeUrl: string;
}

/**
 * Generate cryptographically secure device keys and factory configuration
 */
export async function factoryProvisionDevice(
  input: FactoryProvisioningInput
): Promise<FactoryProvisioningResult> {
  // 1. Generate 256-bit high-entropy secret key
  const rawDeviceKey = crypto.randomBytes(32).toString('hex');

  // 2. Hash device key for cloud storage
  const deviceKeyHash = crypto
    .createHash('sha256')
    .update(rawDeviceKey + 'prithvi_hardware_salt_2026')
    .digest('hex');

  // 3. Format deterministic asset code
  const randomSuffix = crypto.randomBytes(3).toString('hex').toUpperCase();
  const assetCode = `PG-SPEAR-${randomSuffix}`;
  const serialNumber = `SN-2026-${input.macAddress.replace(/[:\-]/g, '').toUpperCase().slice(-8)}`;

  // 4. Create database asset record in PROVISIONED state
  const asset = new PhysicalAsset({
    entityId: new Types.ObjectId(input.entityId),
    facilityId: new Types.ObjectId(input.facilityId),
    parentBoxId: input.parentBoxId ? new Types.ObjectId(input.parentBoxId) : undefined,
    type: 'IOT_NODE',
    assetCode,
    serialNumber,
    name: input.name || `Smart Spear ${assetCode}`,
    status: 'PROVISIONED',
    deviceKey: rawDeviceKey, // Mongoose schema has select: false
    deviceKeyHash,
    hardwareRevision: input.hardwareRevision || 'REV_B_ESP32_A7670C',
    macAddress: input.macAddress.toUpperCase(),
    imei: input.imei,
    simNo: input.simNumber,
    firmwareVersion: 'v1.0.0',
    supercapacitorHealth: {
      voltageMv: 5200,
      vDropBurstMv: 140,
      tegDeltaTC: 0,
      harvestEfficiencyPct: 100,
      estimatedEsrMilliOhms: 70,
      healthScorePct: 100,
      brownoutRisk: 'LOW',
      assessedAt: new Date(),
    },
    lifecycleHistory: [
      {
        fromStatus: 'NONE',
        toStatus: 'PROVISIONED',
        reason: 'Factory flashing and cryptographic provisioning complete',
        changedAt: new Date(),
        changedBy: 'FACTORY_PROVISIONING_CLI',
      },
    ],
  });

  // 5. Generate factory QR code
  const qrCodeUrl = await generateAssetQrUrl('NODE', asset._id.toString(), input.macAddress);
  asset.qrCodeUrl = qrCodeUrl;

  await asset.save();

  // 6. Build NVS flash bundle
  const nvsConfig: NvsConfigBundle = {
    version: 1,
    nodeId: asset._id.toString(),
    assetCode,
    macAddress: input.macAddress.toUpperCase(),
    deviceKey: rawDeviceKey,
    apiEndpoint: 'https://api.prithvigrid.com/api/v1/telemetry/ingest',
    reportingIntervalSeconds: 7200, // 2-hour default sleep cycle
    hardwareRevision: input.hardwareRevision || 'REV_B_ESP32_A7670C',
    provisionedAt: new Date().toISOString(),
  };

  // 7. Generate C-Header template for ESP-IDF / PlatformIO compilation
  const nvsHeaderC = `/**
 * Autogenerated by Prithvi Grid Factory Provisioning Tool
 * Node ID: ${asset._id.toString()}
 * Asset: ${assetCode}
 */
#ifndef PRITHVI_PROVISION_CONFIG_H
#define PRITHVI_PROVISION_CONFIG_H

#define PRITHVI_NODE_ID "${asset._id.toString()}"
#define PRITHVI_ASSET_CODE "${assetCode}"
#define PRITHVI_MAC_ADDR "${input.macAddress.toUpperCase()}"
#define PRITHVI_DEVICE_KEY "${rawDeviceKey}"
#define PRITHVI_API_ENDPOINT "https://api.prithvigrid.com/api/v1/telemetry/ingest"
#define PRITHVI_REPORT_INTERVAL_SEC 7200
#define PRITHVI_HW_REVISION "${input.hardwareRevision || 'REV_B_ESP32_A7670C'}"

#endif // PRITHVI_PROVISION_CONFIG_H
`;

  return {
    asset,
    rawDeviceKey,
    deviceKeyHash,
    nvsConfig,
    nvsHeaderC,
    qrCodeUrl,
  };
}
